"""Tests for reactor.paper.dataset (export + manifest verify)."""
from __future__ import annotations

import json

import pandas as pd
import pytest

from reactor.paper import dataset, settings


@pytest.fixture()
def fake_cache(tmp_path, monkeypatch):
    """A minimal cache tree: one 2D summary with a 598 K row, one case dir."""
    root = tmp_path / "cache" / "draft"
    monkeypatch.setattr(settings, "cache_root", lambda name: tmp_path / "cache" / name)
    monkeypatch.setattr(settings, "validation_dir", lambda: tmp_path / "validation")
    root.mkdir(parents=True)

    case_id = "G1 — GHSV sweep_50"
    summary = pd.DataFrame({
        "Case_ID": [case_id, settings.CASES_598K[0]],
        "X_H2_out": [50.0, 40.0],
        "runtime_s": [10.0, 20.0],
    })
    summary.to_csv(settings.summary_csv("draft", settings.MODEL_2D), index=False)

    for cid in (case_id, settings.CASES_598K[0]):
        case_dir = settings.case_cache_dir("draft", settings.MODEL_2D, cid)
        case_dir.mkdir(parents=True)
        (case_dir / "config.json").write_text("{}")
        (case_dir / "kpis.json").write_text("{}")
    (root / "figures").mkdir()
    (root / "figures" / "fig.png").write_bytes(b"png")
    return tmp_path


def test_export_dry_run_writes_nothing(fake_cache):
    """A dry-run export writes no files but still reports file counts and missing inputs."""
    out = fake_cache / "out"
    report = dataset.export("draft", dry_run=True, out_dir=out)
    assert report["dry_run"] and not out.exists()
    assert report["n_files"] > 0
    # The gaps are reported, never silently dropped.
    assert any("summary_kpis_1d" in m for m in report["missing"])


def test_export_is_complete_and_verify_catches_tampering(fake_cache):
    """The exported dataset keeps every case row (598 K included), and verify() flags any tampered file."""
    out = fake_cache / "out"
    report = dataset.export("draft", include_598k="exclude", out_dir=out)
    assert (out / dataset.MANIFEST_NAME).exists()

    exported = pd.read_csv(out / "kpis" / "summary_kpis_2d.csv")
    assert exported["Case_ID"].isin(settings.CASES_598K).any()
    # The 598 K case directories ship too, whatever the reporting switch.
    assert (out / "fields" / "2d" / settings.CASES_598K[0] / "kpis.json").exists()

    check = dataset.verify(out)
    assert check["ok"], check
    assert check["n_checked"] == report["n_files"]

    # Tamper with one file: verify must fail.
    (out / "figures" / "fig.png").write_bytes(b"tampered")
    check = dataset.verify(out)
    assert not check["ok"]
    assert check["mismatched"] == ["figures/fig.png"]


def test_manifest_records_provenance_and_decisions(fake_cache):
    """The manifest records the D-decisions, git provenance, and the full-sweep 2D runtime including 598 K."""
    out = fake_cache / "out"
    dataset.export("draft", out_dir=out)
    manifest = json.loads((out / dataset.MANIFEST_NAME).read_text())
    assert manifest["include_598k"] == settings.INCLUDE_598K
    assert manifest["whsv_convention"] == settings.WHSV_CONVENTION
    assert manifest["one_d_variant"] == settings.ONE_D_VARIANT
    assert "git_commit" in manifest["provenance"]
    assert manifest["sweep_runtime_2d_s"] == pytest.approx(30.0)  # full sweep incl. 598 K


def test_restore_cache_inverts_export_without_clobbering(fake_cache):
    """restore_cache() rebuilds an empty cache from the dataset tree and never overwrites existing files."""
    out = fake_cache / "out"
    dataset.export("draft", out_dir=out)

    # Existing cache: everything already present is skipped, nothing rewritten.
    report = dataset.restore_cache(out)
    assert report["n_restored"] == 0
    assert report["n_skipped_existing"] > 0

    # Fresh environment: wipe the cache, restore, and the summary + case files are back.
    import shutil as _shutil
    _shutil.rmtree(settings.cache_root("draft"))
    report = dataset.restore_cache(out)
    assert report["resolution"] == "draft" and report["n_restored"] > 0
    assert settings.summary_csv("draft", settings.MODEL_2D).exists()
    case_dir = settings.case_cache_dir("draft", settings.MODEL_2D, "G1 — GHSV sweep_50")
    assert (case_dir / "kpis.json").exists()
    # Figures are regenerated by the notebooks, never restored.
    assert not (settings.cache_root("draft") / "figures").exists()
